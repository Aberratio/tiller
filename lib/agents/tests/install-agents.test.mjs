import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { installAgents } from '../install-agents.mjs'

const fresh = () => mkdtempSync(join(tmpdir(), 'agents-'))

test('writes one agent file per role, with the core path spelled out and no headless-only tool', () => {
  const dir = fresh()
  const r = installAgents({ dir })
  assert.equal(r.status, 'ok')
  assert.ok(r.written.includes('flow-resolver'))
  const md = readFileSync(join(dir, 'flow-resolver.md'), 'utf8')
  assert.match(md, /^---\nname: flow-resolver\n/)
  assert.match(md, /\$TILLER_HOME` in the instructions below is `/)
  assert.doesNotMatch(md, /StructuredOutput/)
})

test('a second run changes nothing', () => {
  const dir = fresh()
  installAgents({ dir })
  const r = installAgents({ dir })
  assert.deepEqual(r.written, [])
})

test('a hand-written file is never overwritten; a predecessor-generated one is', () => {
  const dir = fresh()
  writeFileSync(join(dir, 'flow-resolver.md'), 'mine\n')
  assert.equal(installAgents({ dir }).status, 'refused')
  writeFileSync(join(dir, 'flow-resolver.md'), '<!-- generated by lib/agents/generate.mjs from x -->\n')
  assert.equal(installAgents({ dir }).status, 'ok')
})

test('a profile binding changes the vendor tools a role is written with', () => {
  const dir = fresh()
  assert.equal(installAgents({ dir, tools: { docs: { kind: 'confluence' } } }).status, 'ok')
  const tools = readFileSync(join(dir, 'flow-resolver.md'), 'utf8').match(/^tools: (.*)$/m)[1]
  assert.match(tools, /mcp__claude_ai_Atlassian__getConfluencePage/)
  assert.doesNotMatch(tools, /notion/)
})
