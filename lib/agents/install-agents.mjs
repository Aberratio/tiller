#!/usr/bin/env node
// Writes each harness role from config/agents.json as an agent file, so an interactive session can
// dispatch the role as a subagent. The driver builds roles inline and does not need these files.
//
//   install-agents.mjs [--dir <agents dir>]     default ~/.claude/agents
//
// Idempotent. A file that this script (or its predecessor) did not generate is never overwritten.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { CORE_ROOT, agentDefinition } from '../driver/agents.mjs'

const MARKER = 'generated by lib/agents/install-agents.mjs'
const OLD_MARKERS = ['generated by lib/agents/generate.mjs']
// Tools only a headless lane has; an interactive subagent cannot be given them.
const HEADLESS_ONLY = new Set(['StructuredOutput'])

export function renderAgentFile(name, core = CORE_ROOT) {
  const def = agentDefinition(name, core)
  if (!def) return null
  return [
    '---',
    `name: ${name}`,
    `description: ${def.description}`,
    `tools: ${def.tools.filter(t => !HEADLESS_ONLY.has(t)).join(', ')}`,
    'model: inherit',
    '---',
    '',
    `<!-- ${MARKER} from ${join(core, 'skills', name, 'SKILL.md')}; edits here are overwritten -->`,
    '',
    def.prompt,
  ].join('\n')
}

export function installAgents({ core = CORE_ROOT, dir = join(homedir(), '.claude', 'agents') } = {}) {
  const names = Object.keys(JSON.parse(readFileSync(join(core, 'config', 'agents.json'), 'utf8')))
  const rendered = names.map(name => ({ name, md: renderAgentFile(name, core), path: join(dir, `${name}.md`) }))
  for (const { path } of rendered) {
    if (!existsSync(path)) continue
    const text = readFileSync(path, 'utf8')
    if (![MARKER, ...OLD_MARKERS].some(m => text.includes(m))) {
      return { status: 'refused', reason: `${path} was not generated by the harness; move it aside first` }
    }
  }
  mkdirSync(dir, { recursive: true })
  const written = [], unchanged = []
  for (const { name, md, path } of rendered) {
    if (existsSync(path) && readFileSync(path, 'utf8') === md) { unchanged.push(name); continue }
    writeFileSync(path, md)
    written.push(name)
  }
  return { status: 'ok', dir, written, unchanged }
}

if (process.argv[1] && process.argv[1].endsWith('install-agents.mjs')) {
  const argv = process.argv.slice(2)
  const i = argv.indexOf('--dir')
  const result = installAgents(i === -1 ? {} : { dir: argv[i + 1] })
  process.stdout.write(JSON.stringify(result) + '\n')
  process.exit(result.status === 'ok' ? 0 : 4)
}
