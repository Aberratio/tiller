// Copilot CLI targets for the neutral desired state: tiller's own hooks file, owned items in the
// JSON-with-comments settings.json, the managed block in copilot-instructions.md, skill links and
// rendered role agents.
import { join } from 'node:path'
import { BLOCK_HEADER, forwardSlashes, leaves, shellCommand, shQuote } from './claude.mjs'
import { desiredSkills } from './skills.mjs'
import { CORE_ROOT, roleSpec } from '../driver/agents.mjs'
import { parseTool } from '../driver/adapters/tools.mjs'

// PascalCase hooks match on Claude tool names, which Copilot maps from its own tools.
const KINDS = { read: ['Read'], search: ['Grep', 'Glob'], write: ['Edit', 'Write'], shell: ['Bash'] }

const psQuote = s => `'${String(s).replace(/'/g, "''")}'`

// Written on every OS so one hooks file serves both; `exit $LASTEXITCODE` keeps a wrapper's deny.
function powershellCommand(args, { platform, shell }) {
  const bash = platform === 'win32' ? shell?.posixPath : 'bash'
  if (!bash) throw new Error('a hook on Windows needs Git Bash')
  const paths = platform === 'win32' ? [bash, ...args].map(forwardSlashes) : [bash, ...args]
  return `& ${paths.map(psQuote).join(' ')}; exit $LASTEXITCODE`
}

function hookEntry(hook, env, tillerHome, opts) {
  const matcher = hook.kinds.map(k => {
    if (!KINDS[k]) throw new Error(`hook ${hook.id}: unknown kind "${k}"`)
    return KINDS[k].join('|')
  }).join('|')
  const event = hook.event[0].toUpperCase() + hook.event.slice(1)
  // Copilot reads a PreToolUse decision at the top level, so a Claude-format hook runs behind a translator.
  const args = event === 'PreToolUse' ? [join(tillerHome, 'lib', 'hooks', 'copilot-pretooluse.sh'), hook.command] : [hook.command]
  const bash = shellCommand(args, opts)
  const powershell = powershellCommand(args, opts)
  // A Copilot hook that times out lets the call through, so it gets four times the 30 s default.
  const entry = { type: 'command', matcher, bash, powershell, timeoutSec: 120 }
  if (Object.keys(env).length) entry.env = { ...env }
  return { event, entry }
}

export function copilotTargets(desired, { configDir, tillerHome, platform, shell }) {
  const env = desired.env ?? {}
  const byEvent = new Map()
  for (const hook of desired.hooks ?? []) {
    const { event, entry } = hookEntry(hook, env, tillerHome, { platform, shell })
    byEvent.set(event, [...(byEvent.get(event) ?? []), entry])
  }
  const hookItems = byEvent.size
    ? [{ id: '/version', value: 1 }, ...[...byEvent].map(([event, entries]) => ({ id: `/hooks/${event}`, value: entries }))]
    : []
  const body = desired.instructions?.body ? `${BLOCK_HEADER}\n${desired.instructions.body}` : BLOCK_HEADER
  return [
    { path: join(configDir, 'hooks', 'tiller.json'), kind: 'json', items: hookItems },
    { path: join(configDir, 'settings.json'), kind: 'jsonc', items: leaves(desired.native?.copilot ?? {}) },
    { path: join(configDir, 'copilot-instructions.md'), kind: 'block', body },
  ]
}

// Copilot has no global env setting; hooks get env per entry and the shell gets these lines.
export const copilotEnvLines = (desired, platform) => Object.entries(desired.env ?? {}).map(([k, v]) =>
  (platform === 'win32' ? `[Environment]::SetEnvironmentVariable(${psQuote(k)}, ${psQuote(v)}, 'User')` : `export ${k}=${shQuote(v)}`))

const TOOLS = { shell: 'execute', read: 'read', search: 'search', web: 'web' }
const MAX_BODY = 30000

// Model is left out: Copilot inherits its default, and the roles name Claude model aliases.
export function renderCopilotAgent(name, core = CORE_ROOT) {
  const role = roleSpec(name, core)
  if (!role) throw new Error(`role agent ${name} is not in config/agents.json`)
  const tools = role.tools.map(parseTool).map(t => (t.kind === 'mcp' ? `${t.server}/${t.tool}` : TOOLS[t.kind]))
  const body = `<!-- generated by tiller apply from ${join(core, 'skills', name, 'SKILL.md')}; edits here are reported as drift -->\n\n${role.systemPrompt}`
  if (body.length > MAX_BODY) throw new Error(`role agent ${name}: ${body.length} characters, Copilot reads at most 30,000`)
  return ['---', `name: ${name}`, `description: ${JSON.stringify(role.description)}`, 'tools:', ...tools.map(t => `  - ${JSON.stringify(t)}`), '---', '', body].join('\n')
}

export function copilotLinks(desired, { configDir, home, tillerHome, personalDir = null }) {
  return [
    ...desiredSkills({ tillerHome, personalDir }).map(({ name, source }) =>
      ({ kind: 'skill', mode: 'symlink', name, dest: join(home, '.agents', 'skills', name), source })),
    ...(desired.agents ?? []).map(name =>
      ({ kind: 'agent', mode: 'rendered', name, dest: join(configDir, 'agents', `${name}.agent.md`), text: renderCopilotAgent(name, tillerHome) })),
  ]
}
